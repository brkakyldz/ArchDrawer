import { test, expect, auth, makeDiagram, createDiagram, document, library, item, content } from './helpers';

test('H12 [DM-1, DM-2, DM-3, PER-1, PER-2] library rename, duplicate, confirmed delete and imports preserve unrelated documents', async ({ page, request, token }) => {
  const first = await createDiagram(request, token, makeDiagram('First review'));
  const second = await createDiagram(request, token, makeDiagram('Second review'));
  await page.goto('/');
  await item(page, first.id).getByTestId('library-rename').click();
  await page.getByTestId('library-rename-input').fill('Discarded library title');
  await page.getByTestId('library-rename-input').press('Escape');
  await expect(item(page, first.id).getByTestId('library-item-title')).toHaveText('First review');
  await item(page, first.id).getByTestId('library-rename').click();
  await page.getByTestId('library-rename-input').fill('Accepted checkout review');
  await page.getByTestId('library-rename-input').press('Enter');
  await expect(item(page, first.id).getByTestId('library-item-title')).toHaveText('Accepted checkout review');
  await expect.poll(async () => (await document(request, first.id)).title).toBe('Accepted checkout review');
  const renamed = await document(request, first.id);
  const mismatched = await request.put(`/api/diagrams/${first.id}`, { headers: auth(token), data: { ...renamed, id: second.id } });
  expect(mismatched.status()).toBe(400);
  expect((await mismatched.json()).error).toMatch(/id/i);
  expect(await document(request, first.id)).toEqual(renamed);
  const entries = await library(request);
  expect(entries.map(entry => Date.parse(entry.updatedAt))).toEqual(entries.map(entry => Date.parse(entry.updatedAt)).sort((a, b) => b - a));
  await expect.poll(() => page.getByTestId('library-item').evaluateAll(elements => elements.map(element => element.getAttribute('data-diagram-id')))).toEqual(entries.map(entry => entry.id));
  expect(entries.find(entry => entry.id === first.id)).toMatchObject({ title: renamed.title, source: renamed.source, updatedAt: renamed.updatedAt });
  const knownIds = new Set(entries.map(entry => entry.id));
  await item(page, first.id).getByTestId('library-duplicate').click();
  let copyId = '';
  await expect.poll(async () => {
    const additions = (await library(request)).filter(entry => !knownIds.has(entry.id));
    if (additions.length === 1) copyId = additions[0].id;
    return additions.map(entry => entry.title);
  }).toEqual(['Accepted checkout review (copy)']);
  const copy = await document(request, copyId);
  expect(copy.id).not.toBe(first.id);
  expect(content(copy)).toEqual({ ...content(renamed), title: `${renamed.title} (copy)` });
  await expect(item(page, copyId).getByTestId('library-item-title')).toHaveText('Accepted checkout review (copy)');
  const dismiss = page.waitForEvent('dialog').then(async dialog => { expect(dialog.type()).toBe('confirm'); await dialog.dismiss(); });
  await item(page, copyId).getByTestId('library-delete').click();
  await dismiss;
  expect(await document(request, copyId)).toEqual(copy);
  await expect(item(page, copyId)).toBeVisible();
  const accept = page.waitForEvent('dialog').then(async dialog => { expect(dialog.type()).toBe('confirm'); await dialog.accept(); });
  await item(page, copyId).getByTestId('library-delete').click();
  await accept;
  await expect(item(page, copyId)).toHaveCount(0);
  expect((await request.get(`/api/diagrams/${copyId}`)).status()).toBe(404);
  expect(await document(request, second.id)).toEqual(second);
  const valid = makeDiagram('Imported incident map');
  await page.getByTestId('import-input').setInputFiles({ name: 'incident.archdraw.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(valid)) });
  await expect(page).toHaveURL(/\/d\/d_[a-z0-9]{6,}$/);
  const importedId = new URL(page.url()).pathname.slice(3);
  await expect(page.getByTestId('diagram-title')).toHaveText(valid.title);
  expect(content(await document(request, importedId))).toEqual(content(valid));
  await page.getByTestId('back-to-library').click();
  const beforeInvalid = await library(request);
  const dangling = makeDiagram();
  dangling.edges[0].to = 'missing-node';
  const duplicate = makeDiagram();
  duplicate.nodes.push({ ...duplicate.nodes[0] });
  const tooLong = makeDiagram();
  tooLong.nodes[0].label = 'x'.repeat(81);
  const badKind = makeDiagram();
  badKind.nodes[0].kind = 'unrecognised-kind';
  const invalidInputs = ['{ not valid JSON', JSON.stringify({ ...valid, schema: 'archdraw/diagram@999' }), JSON.stringify(dangling), JSON.stringify(duplicate), JSON.stringify(tooLong), JSON.stringify(badKind)];
  for (let i = 0; i < invalidInputs.length; i++) {
    if (i > 0) {
      const invalid = await request.post('/api/diagrams', { headers: auth(token), data: JSON.parse(invalidInputs[i]) });
      expect(invalid.status()).toBe(400);
      expect((await invalid.json()).error).toMatch(/\S+/);
    }
    await page.reload();
    await expect(page.getByTestId('form-error')).not.toBeVisible();
    await page.getByTestId('import-input').setInputFiles({ name: `bad-${i}.json`, mimeType: 'application/json', buffer: Buffer.from(invalidInputs[i]) });
    await expect(page.getByTestId('form-error')).toBeVisible();
    await expect(page.getByTestId('form-error')).toHaveText(/\S+/);
    await expect(page).toHaveURL(/\/$/);
    expect(await library(request)).toEqual(beforeInvalid);
  }
  expect(await document(request, first.id)).toEqual(renamed);
  await item(page, first.id).getByTestId('library-open').click();
  await expect(page).toHaveURL(new RegExp(`/d/${first.id}$`));
  await expect(page.getByTestId('diagram-title')).toHaveText(renamed.title);
  await page.goto('/d/d_doesnotexist');
  await expect(page.getByTestId('not-found')).toBeVisible();
  await expect(page.getByTestId('editor')).toHaveCount(0);
});
