import { test, expect, makeDiagram, createDiagram, openEditor, saved, drag, connect } from './helpers';

test('H08 [DM-3, EDT-1, EDT-3, EDT-4, EDT-5, PER-1] dragging, grouping and handle connections support reversible selection deletion', async ({ page, request, token }) => {
  const draft = makeDiagram('Interaction review');
  draft.groups.push({ id: 'zone', label: 'Processing zone', parent: null, x: 620, y: 410, w: 330, h: 240 });
  const original = await createDiagram(request, token, draft);
  await openEditor(page, original.id);
  await drag(page, 'node-web', 35, 40);
  await drag(page, 'note-explanation', 45, 25);
  await drag(page, 'group-label', 15, 15);
  let latest = await saved(page, request, original.id, diagram => diagram.nodes.find(node => node.id === 'web')!.x !== original.nodes[0].x && diagram.notes[0].x !== original.notes[0].x && diagram.groups[0].x !== original.groups[0].x);
  expect(latest.notes[0].text).toBe('Orders are durable');
  await connect(page, 'api', 'db');
  latest = await saved(page, request, original.id, diagram => diagram.edges.some(edge => edge.from === 'api' && edge.to === 'db'));
  const connected = latest.edges.find(edge => edge.from === 'api' && edge.to === 'db')!;
  expect(connected.style).toBe('call');
  expect(latest.edges).toHaveLength(2);
  expect(latest.edges.some(edge => edge.from === edge.to)).toBe(false);
  const nodeBox = (await page.getByTestId('node-api').boundingBox())!;
  const groupBox = (await page.getByTestId('group-zone').boundingBox())!;
  const startX = nodeBox.x + nodeBox.width / 2;
  const startY = nodeBox.y + Math.min(18, nodeBox.height / 2);
  await drag(page, 'node-api', groupBox.x + groupBox.width / 2 - startX, groupBox.y + groupBox.height / 2 - startY);
  await saved(page, request, original.id, diagram => diagram.nodes.find(node => node.id === 'api')!.group === 'zone');
  const inside = (await page.getByTestId('node-api').boundingBox())!;
  await drag(page, 'node-api', startX - (inside.x + inside.width / 2), startY - (inside.y + Math.min(18, inside.height / 2)));
  await saved(page, request, original.id, diagram => diagram.nodes.find(node => node.id === 'api')!.group === null);
  await page.getByTestId('node-api').click();
  await page.getByTestId('node-db').click({ modifiers: ['Shift'] });
  await page.getByTestId('tool-delete').click();
  latest = await saved(page, request, original.id, diagram => diagram.nodes.length === 1);
  expect(latest.nodes[0].id).toBe('web');
  expect(latest.edges).toEqual([]);
  await expect(page.getByTestId('node-api')).toHaveCount(0);
  await expect(page.getByTestId('node-db')).toHaveCount(0);
  await expect(page.getByTestId('node-web')).toBeVisible();
  await page.getByTestId('tool-undo').click();
  await saved(page, request, original.id, diagram => diagram.nodes.length === 3 && diagram.edges.length === 2);
  await page.getByTestId('note-explanation').click();
  await page.getByTestId('tool-delete').click();
  latest = await saved(page, request, original.id, diagram => diagram.notes.length === 0);
  expect(latest.groups).toHaveLength(1);
  await page.getByTestId('tool-undo').click();
  await saved(page, request, original.id, diagram => diagram.notes.length === 1);
  await page.getByTestId('group-zone').getByTestId('group-label').click();
  await page.getByTestId('tool-delete').click();
  latest = await saved(page, request, original.id, diagram => diagram.groups.length === 0);
  expect(latest.nodes).toHaveLength(3);
  expect(latest.edges).toHaveLength(2);
  await page.getByTestId('tool-undo').click();
  await saved(page, request, original.id, diagram => diagram.groups.length === 1);
});
