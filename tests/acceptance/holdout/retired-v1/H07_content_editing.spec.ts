import { test, expect, createDiagram, openEditor, saved, document, inline } from './helpers';

test('H07 [DM-1, DM-2, EDT-2, EDT-3, PER-1] inline text, inspector fields and toolbar additions persist without losing existing content', async ({ page, request, token }) => {
  const original = await createDiagram(request, token);
  await openEditor(page, original.id);
  await inline(page, 'diagram-title', 'diagram-title-input', 'Checkout design review');
  await inline(page, 'diagram-subtitle', 'diagram-subtitle-input', 'Reviewed with the platform team');
  await inline(page, 'node-api', 'node-label-input', 'Checkout gateway');
  await page.getByTestId('node-api').dblclick();
  await page.getByTestId('node-label-input').fill('Discard this rename');
  await page.getByTestId('node-label-input').press('Escape');
  await expect(page.getByTestId('node-api').getByTestId('node-label')).toHaveText('Checkout gateway');
  await page.getByTestId('node-api').click();
  await page.getByTestId('inspector-label').fill('Checkout API');
  await page.getByTestId('inspector-kind').selectOption('gate');
  await page.getByTestId('inspector-tech').fill('Node 22');
  await page.getByTestId('inspector-description').fill('Validates and accepts a checkout');
  await page.getByTestId('inspector-description').press('Tab');
  let latest = await saved(page, request, original.id, diagram => {
    const api = diagram.nodes.find(node => node.id === 'api')!;
    return diagram.title === 'Checkout design review' && diagram.subtitle === 'Reviewed with the platform team' && api.label === 'Checkout API' && api.kind === 'gate' && api.tech === 'Node 22' && api.description === 'Validates and accepts a checkout';
  });
  await expect(page.getByTestId('node-api')).toHaveAttribute('data-kind', 'gate');
  await expect(page.getByTestId('node-api').getByTestId('node-tech')).toHaveText('Node 22');
  await expect(page.getByTestId('node-api').getByTestId('node-description')).toHaveText('Validates and accepts a checkout');
  for (const kind of ['actor', 'ui', 'service', 'llm', 'external', 'data', 'gate']) {
    const oldIds = new Set(latest.nodes.map(node => node.id));
    await page.getByTestId('tool-add-node').click();
    await expect(page.getByTestId('inspector-label')).toHaveValue('New component');
    await expect(page.getByTestId('inspector-kind')).toHaveValue('service');
    await page.getByTestId('inspector-label').fill(`Review ${kind}`);
    await page.getByTestId('inspector-kind').selectOption(kind);
    latest = await saved(page, request, original.id, diagram => diagram.nodes.some(node => !oldIds.has(node.id) && node.kind === kind && node.label === `Review ${kind}`));
  }
  const oldGroups = new Set(latest.groups.map(group => group.id));
  await page.getByTestId('tool-add-group').click();
  latest = await saved(page, request, original.id, diagram => diagram.groups.some(group => !oldGroups.has(group.id) && group.label === 'New group'));
  const group = latest.groups.find(group => !oldGroups.has(group.id))!;
  await page.getByTestId(`group-${group.id}`).getByTestId('group-label').dblclick();
  await page.getByTestId('group-label-input').fill('Operations');
  await page.getByTestId('group-label-input').press('Enter');
  const oldNotes = new Set(latest.notes.map(note => note.id));
  await page.getByTestId('tool-add-note').click();
  latest = await saved(page, request, original.id, diagram => diagram.notes.some(note => !oldNotes.has(note.id) && note.text === 'Note'));
  const note = latest.notes.find(note => !oldNotes.has(note.id))!;
  await page.getByTestId(`note-${note.id}`).dblclick();
  await page.getByTestId('note-input').fill('Review before deployment\nKeep the rollback plan nearby.');
  await page.getByTestId('note-input').press(`${process.platform === 'darwin' ? 'Meta' : 'Control'}+Enter`);
  latest = await saved(page, request, original.id, diagram => diagram.groups.some(candidate => candidate.id === group.id && candidate.label === 'Operations') && diagram.notes.some(candidate => candidate.id === note.id && candidate.text.includes('rollback plan')));
  expect(latest.nodes).toHaveLength(original.nodes.length + 7);
  expect(latest.edges).toEqual(original.edges);
  expect(latest.notes.find(note => note.id === 'explanation')).toEqual(original.notes[0]);
  expect(latest.nodes.some(node => node.label === 'Discard this rename')).toBe(false);
  await page.reload();
  await expect(page.getByTestId('diagram-title')).toHaveText('Checkout design review');
  await expect(page.getByTestId('diagram-subtitle')).toHaveText('Reviewed with the platform team');
  await expect(page.getByTestId(`group-${group.id}`).getByTestId('group-label')).toHaveText('Operations');
  await expect(page.getByTestId(`note-${note.id}`)).toContainText('rollback plan');
  expect(await document(request, original.id)).toEqual(latest);
});
