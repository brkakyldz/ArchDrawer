"""Generate src/core/metrics.generated.ts from the bundled Geist fonts.

Advance widths in em of every character in CHARS, for Geist at weights 400, 500 and 600
(instanced from the variable font), and the fixed advance of Geist Mono. CHARS is Latin-1,
Latin Extended-A, some punctuation, and the Greek and Cyrillic letters Geist draws itself;
text.ts gives every other character a fallback width.

    python scripts/font-metrics.py          # needs fontTools and brotli (pip install fonttools brotli)

Regenerating with unchanged fonts must give an empty diff.
"""
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "src" / "web" / "fonts"
OUT = ROOT / "src" / "core" / "metrics.generated.ts"
_GEIST = TTFont(FONTS / "Geist-Variable.woff2").getBestCmap()
CHARS = (
    "".join(chr(c) for c in range(0x20, 0x7F))
    + "".join(chr(c) for c in range(0xA0, 0x180))
    + "–—‘’“”…•→←↑↓·×"
    # Greek and Cyrillic: only what Geist has. A Greek letter it lacks comes from a fallback font.
    + "".join(chr(c) for c in range(0x370, 0x500) if c in _GEIST)
)


def advances(weight: int) -> list[float]:
    font = instantiateVariableFont(TTFont(FONTS / "Geist-Variable.woff2"), {"wght": weight})
    cmap = font.getBestCmap()
    hmtx = font["hmtx"].metrics
    upm = font["head"].unitsPerEm
    # A character the font lacks is measured as wide (0.62 em), the same fallback text.ts uses.
    return [round(hmtx[cmap[ord(c)]][0] / upm, 4) if ord(c) in cmap else 0.62 for c in CHARS]


def mono_advance() -> float:
    font = TTFont(FONTS / "GeistMono-Variable.woff2")
    cmap = font.getBestCmap()
    widths = {font["hmtx"].metrics[cmap[ord(c)]][0] for c in "0aMW/._" if ord(c) in cmap}
    assert len(widths) == 1, f"Geist Mono is not fixed-width: {widths}"
    return round(widths.pop() / font["head"].unitsPerEm, 4)


def ts_array(values: list[float]) -> str:
    return "[" + ", ".join(f"{v:g}" for v in values) + "]"


def main() -> None:
    chars = CHARS.replace("\\", "\\\\").replace('"', '\\"')
    lines = [
        "// Generated by scripts/font-metrics.py from the bundled Geist and Geist Mono",
        "// (src/web/fonts), advance widths in em. Do not edit by hand.",
        f'export const METRIC_CHARS = "{chars}";',
        f"export const GEIST_400: readonly number[] = {ts_array(advances(400))};",
        f"export const GEIST_500: readonly number[] = {ts_array(advances(500))};",
        f"export const GEIST_600: readonly number[] = {ts_array(advances(600))};",
        f"export const MONO_ADVANCE = {mono_advance():g};",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(CHARS)} characters)")


if __name__ == "__main__":
    main()
